"""Write evaluation configs for a fine-tuned checkpoint, one per test set of the tasks it was trained on.

    python -m finetune.make_eval_configs runs/shared_lora/best                 # test sets -> configs/finetuned/
    python -m finetune.make_eval_configs runs/shared_lora/step-1500 --split val   # in-domain val, for selection
    bash scripts/run_eval_configs.sh configs/finetuned/shared_lora-best           # run them all

Each config is a copy of the zero-shot config (same data, prompt, decoder and metric) with:
  * generation_version = ft-<tag>-<original version>, so outputs never mix with the baseline's;
  * model.options.adapter_path = the checkpoint, plus the steps / initial noise it was trained for;
  * a bf16 transformer when the method cannot run on the NF4 base (LoKr / LoHa / partial), with a note;
  * paths that were relative to configs/ made absolute (the copies live in a subfolder).
`coco_pose_qwen` (pose preservation) is always added: it checks that the model can still edit photos.
"""

from __future__ import annotations

import argparse
import copy
from pathlib import Path

import yaml

from finetune.config import REPO_ROOT
from visionbench.models import adapters

CONFIGS = REPO_ROOT / "configs"
TEST_CONFIGS = {
    "segmentation": ["indomain_nyuv2_semseg_all", "indomain_nyuv2_semseg_present", "indomain_vkitti2_semseg_all",
                     "indomain_vkitti2_semseg_present", "full_qwen_cityscapes_all", "full_qwen_cityscapes_present",
                     "full_qwen_ade20k"],
    "depth": ["qwen_nyuv2_depth", "indomain_vkitti2_depth", "diode_depth"],
    "normals": ["qwen_normal_nyuv2", "qwen_normal_ibims", "qwen_normal_diode"],
    "pose": ["coco_pose_estimation"],
}
EDITING_CHECK = "coco_pose_qwen"
# In-domain configs that read the fine-tuning store, so they can be pointed at its val split.
VAL_CONFIGS = {
    "segmentation": ["indomain_nyuv2_semseg_all", "indomain_vkitti2_semseg_all"],
    "depth": ["indomain_vkitti2_depth"],
}
BF16_MODEL = {"profile": "custom", "options": {"transformer_precision": "bf16", "text_encoder_precision": "bf16",
                                               "text_encoder_cpu_offload": True, "vae_precision": "bf16"}}


def make(adapter_dir: Path, tag: str, split: str, out_root: Path, names: list[str] | None = None) -> list[Path]:
    adapter_dir = adapter_dir.resolve()
    adapter = adapters.read_config(adapter_dir)
    tasks = adapter.get("tasks") or list(TEST_CONFIGS)
    if names is None:
        table = VAL_CONFIGS if split == "val" else TEST_CONFIGS
        names = [n for task in tasks for n in table.get(task, [])]
        if split == "test":
            names.append(EDITING_CHECK)
    if not names:
        raise SystemExit(f"no {split} configs for tasks {tasks} (val configs exist for {sorted(VAL_CONFIGS)})")
    out_dir = out_root / tag
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name in names:
        source = CONFIGS / f"{name}.yaml"
        if not source.is_file():
            raise SystemExit(f"{source} does not exist")
        data = yaml.safe_load(source.read_text(encoding="utf-8"))
        written.append(_write(data, source, name, adapter, adapter_dir, tag, split, out_dir))
    return written


def _write(data: dict, source: Path, name: str, adapter: dict, adapter_dir: Path, tag: str, split: str,
           out_dir: Path) -> Path:
    data = copy.deepcopy(data)
    notes = [f"Generated by finetune.make_eval_configs from configs/{name}.yaml for {adapter_dir}"]
    for key in ("output_root",):
        data[key] = str((source.parent / data[key]).resolve())
    model = data["model"]
    model["cache_dir"] = str((source.parent / model.get("cache_dir", "model-cache")).resolve())
    options = model.setdefault("options", {})
    precision = options.get("transformer_precision", "nf4" if model.get("profile") == "vram_16gb" else "bf16")
    if adapter["method"] not in adapters.QUANTIZATION_SAFE and precision in {"int8", "nf4"}:
        model["profile"] = BF16_MODEL["profile"]
        options.update(BF16_MODEL["options"])
        notes.append(f"transformer switched from {precision} to bf16 ({adapter['method']} cannot run on a quantized "
                     f"base); the zero-shot baseline of this config used {precision}, rerun it in bf16 for a strict "
                     "comparison")
    inference = adapter.get("inference") or {}
    options["num_inference_steps"] = int(inference.get("num_inference_steps", options.get("num_inference_steps", 40)))
    options["init_noise"] = inference.get("init_noise", "gaussian")
    options["adapter_path"] = str(adapter_dir)
    data["generation_version"] = f"ft-{tag}-{data['generation_version']}"
    if split == "val":
        params = data["dataset"].setdefault("params", {})
        if "split" not in params:
            raise SystemExit(f"{name} has no dataset.params.split; it cannot be evaluated on val")
        params["split"] = "val"
        data["generation_version"] = f"{data['generation_version']}-val"
    target = out_dir / f"{name}{'_val' if split == 'val' else ''}.yaml"
    header = "".join(f"# {line}\n" for line in notes)
    target.write_text(header + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("adapter", type=Path, help="checkpoint directory (runs/<name>/best, step-<n>, final)")
    parser.add_argument("--tag", help="name used in generation_version and the output folder "
                                      "(default: <run>-<checkpoint>, e.g. shared_lora-best)")
    parser.add_argument("--split", choices=["test", "val"], default="test")
    parser.add_argument("--configs", nargs="+", help="only these config names (default: all for the trained tasks)")
    parser.add_argument("--out", type=Path, default=CONFIGS / "finetuned")
    args = parser.parse_args(argv)
    tag = args.tag or f"{args.adapter.resolve().parent.name}-{args.adapter.resolve().name}"
    for path in make(args.adapter, tag, args.split, args.out, args.configs):
        print(path)


if __name__ == "__main__":
    main()
